from pydantic import BaseModel, Field
from typing import Optional
from datetime import datetime

class PredictionRequest(BaseModel):
    # Section 1: Sensor Type
    part_number: str = Field(..., description="Part number from selection", example="PCA 1.2005.10S 10")
    resistance: int = Field(..., description="Sensor resistance in ohms (e.g., 100, 500, 1000)", example=100)
    sensor_type: str = Field(..., description="Type of sensor (T-type, E-type, H-type)", example="T-type")
    has_nt_step: bool = Field(..., description="Whether the sensor has NT step processing")

    # Section 2: Sputter / Pre-Laser Data
    sputter_machine: str = Field(..., description="Sputter machine used (Senvac, FHR)", example="Senvac")
    film_thickness: float = Field(..., description="Film thickness in nm", example=15.5)
    sheet_resistance: float = Field(..., description="Sheet resistance in ohms/sq", example=4.5)
    tcr_sputter: float = Field(..., description="TCR (Sputter) in 10^-3 C^-1", example=3.2)
    substrate_batch: str = Field(..., description="Substrate batch number", example="BATCH-99A")
    pt_r20_value: float = Field(..., description="Pre-Test R20 value in ohms", example=102.5)

    # Section 3: Screen Printing (Optional)
    paste_lot_ds1: Optional[str] = Field(None, description="Paste Lot DS1 code")
    paste_lot_ds2: Optional[str] = Field(None, description="Paste Lot DS2 code")
    ds1_viscosity: Optional[float] = Field(None, description="DS1 Viscosity in Pa·s")
    ds2_viscosity: Optional[float] = Field(None, description="DS2 Viscosity in Pa·s")
    air_humidity: Optional[float] = Field(None, description="Air humidity in %")


class PredictionResponse(BaseModel):
    id: int
    timestamp: datetime
    
    # Original Inputs Echoed
    part_number: str
    resistance: int
    sensor_type: str
    has_nt_step: bool
    sputter_machine: str
    film_thickness: float
    sheet_resistance: float
    tcr_sputter: float
    substrate_batch: str
    pt_r20_value: float
    
    # Effective Parameters Used (actual input or historical average fallback)
    effective_ds1_viscosity: float
    effective_ds2_viscosity: float
    effective_air_humidity: float
    
    # Outputs
    recommended_nc_value: float
    model_version: Optional[str] = None
    is_ai_generated: bool = True
    compliance_disclaimer: str = "This prediction is generated by an AI machine learning model trained on historical laser trimming orders and is subject to human verification under EU AI Act transparency requirements."

    class Config:
        from_attributes = True
